def sumop(a,b):
    print("sum of {} and {} is equal to {}".format(a,b,a+b))
def subop(a,b):
    print("difference of {} and {} is equal to {}".format(a,b,a-b))
def mulop(a,b):
    print("product of {} and {} is equal to {}".format(a,b,a*b))
def divop(a,b):
    print("division of {} and {} is equal to {}".format(a,b,a/b))
def mod_divop(a,b):
    print("modulo division of {} and {} is equal to {}".format(a,b,a%b))
def floordivop(a,b):
    print("floor division of {} and {} is equal to {}".format(a,b,a//b))
def exponential(a,b):
    print("exponential of {} and {} is equal to {}".format(a,b,a**b))
    